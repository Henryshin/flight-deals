"""사주 용어 사전 + 태깅. 게시물 더미를 '지식' 코퍼스로 바꾸는 핵심 부가가치.

설계상 가장 큰 함정은 **1글자/일상어 용어의 오탐**이다.
- 오행의 목/화/토/금/수 는 일상 한국어에 극히 흔한 음절이다 ('목요일', '화요일',
  '토요일', '금요일', '수요일' 만 해도 매주 나온다).
- 십신의 '상관' 은 '상관없다/상관관계' 로 훨씬 자주 쓰인다.
따라서 용어를 두 갈래로 나눈다.
- DIRECT_TERMS : 다글자·고유해서 부분문자열 매칭으로 안전한 것
- CONTEXT_TERMS: 문맥 정규식을 만족해야만 인정하는 것
"""
import re

# ---- 문맥 없이도 안전한 다글자 용어 ----
DIRECT_TERMS = {}


def _add(group, terms):
    for t in terms:
        DIRECT_TERMS.setdefault(t, group)


# 오행: 한자는 그 자체로 모호하지 않고, 상생/상극은 다글자라 안전하다.
_add("오행", [
    "오행", "상생", "상극", "음양",
    "木", "火", "土", "金", "水",
    "목생화", "화생토", "토생금", "금생수", "수생목",
    "목극토", "토극수", "수극화", "화극금", "금극목",
])

# 천간: 단독 '갑/을/병/신' 은 위험하지만, 사주 문헌의 표준 표기인
# '천간+오행' 2글자 조합(갑목·병화…)은 사실상 사주 맥락에서만 쓰인다.
_add("천간", [
    "천간", "십간",
    "갑목", "을목", "병화", "정화", "무토", "기토", "경금", "임수", "계수",
    "甲", "乙", "丙", "丁", "戊", "己", "庚", "辛", "壬", "癸",
])

# 지지: 마찬가지로 2글자 조합과 삼합/방합 묶음만 인정.
_add("지지", [
    "지지", "십이지", "지장간",
    "인목", "묘목", "진토", "사화", "오화", "미토", "유금", "술토", "해수", "자수", "축토",
    "인묘진", "사오미", "신유술", "해자축", "자오묘유", "인신사해", "진술축미",
    "子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥",
])

# 십신: '상관' 만 별도 문맥 처리(아래), 나머지는 사주 밖에서 잘 안 쓰인다.
_add("십신", [
    "십신", "육친",
    "비견", "겁재", "식신", "편재", "정재", "편관", "정관", "편인", "정인",
    "칠살", "인성", "재성", "관성", "식상", "비겁",
])

_add("격국", [
    "격국", "건록격", "양인격", "식신격", "상관격", "편재격", "정재격",
    "편관격", "정관격", "편인격", "정인격", "종격", "화격",
])

_add("신살", [
    "신살", "도화살", "역마살", "화개살", "백호살", "괴강살", "원진살",
    "귀문관살", "천을귀인", "문창귀인", "양인", "공망", "삼재",
])

_add("구조", [
    "사주", "팔자", "사주팔자", "명리", "명리학", "일간", "일주", "월주", "연주", "시주",
    "월지", "일지", "연지", "시지", "년주", "년지",
    "대운", "세운", "용신", "기신", "희신", "한신", "구신",
    "신강", "신약", "조후", "합충", "삼합", "육합", "방합", "충형파해",
    "만세력", "십이운성", "장생", "제왕", "묘운",
])

# ---- 문맥을 요구하는 용어 ----
# 값: (그룹, 정규식). 정규식이 본문에서 하나라도 걸려야 태그를 붙인다.
_OHAENG_CONTEXT = "기운|일간|일주|오행|기가|과다|부족|의\\s*기운|이\\s*강|이\\s*약"

CONTEXT_TERMS = {}
for _el in ("목", "화", "토", "금", "수"):
    CONTEXT_TERMS[_el] = (
        "오행",
        re.compile(
            # '목 기운', '목일간', '목이 강한' …  또는  '오행 … 목'
            rf"{_el}\s*(?:{_OHAENG_CONTEXT})"
            rf"|오행[^\n]{{0,8}}{_el}(?:\s|$|[,.\)])"
        ),
    )

# '상관없다 / 상관있다 / 상관관계' 를 걸러낸 뒤에만 십신 상관으로 인정.
CONTEXT_TERMS["상관"] = (
    "십신",
    re.compile(r"상관(?!\s*(?:없|있|관계|치))"),
)

# '신금' 은 천간(辛)과 지지(申) 양쪽에서 쓰이지만 사주 용어인 것은 확실하므로
# 천간으로 통일해 둔다 (그룹 정확도보다 태깅 누락 방지를 우선).
DIRECT_TERMS.setdefault("신금", "천간")

# 그룹 표시 순서 (stats 출력 안정화용)
GROUP_ORDER = ("구조", "오행", "천간", "지지", "십신", "격국", "신살")


def tag_terms(text):
    """본문에서 사주 용어를 찾아 (용어목록, 그룹목록) 반환. 둘 다 정렬된 유니크.

    긴 용어가 짧은 용어를 포함하는 경우(예: '상관격' ⊃ '상관')에도 각각 독립적으로
    센다 — 코퍼스 검색에서 '상관' 으로도 '상관격' 으로도 찾히는 편이 유용하다.
    """
    if not text:
        return [], []
    found = {}
    for term, group in DIRECT_TERMS.items():
        if term in text:
            found[term] = group
    for term, (group, pattern) in CONTEXT_TERMS.items():
        if pattern.search(text):
            found[term] = group
    terms = sorted(found)
    groups = [g for g in GROUP_ORDER if g in set(found.values())]
    return terms, groups


def is_single_char_term(term):
    """1글자 용어인지 (품질 점수에서 가중치를 낮추는 데 쓴다)."""
    return len(term) == 1
